// 依「年級」自動判斷「部別」，對應「部別、班級資料」參考表的分類方式。
//
// 【年級文字統一說明】全系統（校務行政系統＋排課系統）的年級文字一律用「初一/初二/初三」
// 「高一/高二/高三」（不加「中」字），這裡就是唯一的正確清單來源，不要再出現「初中一」
// 「高中一」這種帶「中」字的寫法（舊寫法曾經跟這裡對不上，會導致「科目與比重設定(現況)」
// 下載時初中/高中的資料整批消失、「排課系統」匯入時報「找不到對應年級」，已修正並統一）。
export function departmentForGrade(gradeLevel: string): string {
  const g = gradeLevel.trim();
  if (['幼甲', '幼乙'].includes(g)) return '幼兒園';
  if (['1年', '2年', '3年', '4年', '5年', '6年'].includes(g)) return '國小';
  if (['初一', '初二', '初三'].includes(g)) return '國中';
  if (['高一', '高二', '高三'].includes(g)) return '高中';
  return '其他';
}

