-- 91. 考試分班：新增「不擔任考場班級」設定
-- ------------------------------------------------------------
-- 教務處可以在【考試分班】頁勾選某些班級「不擔任考場」（例如教室不適合當考場），
-- 下面的考場清單會自動排除這些班級。這裡只是新增一個欄位，用 add column if not exists
-- 是可以重複執行的安全寫法，不會動到已經存在的考試/考場資料。
-- 需先執行過 sql/90exam_seating.sql。
-- ============================================================

alter table exam_sessions add column if not exists excluded_class_ids uuid[] not null default '{}'::uuid[];
