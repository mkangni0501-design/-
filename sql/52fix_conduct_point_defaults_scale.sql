-- 52. 出缺席扣分點數：修正成跟「成績單外頁說明」一致的數值
-- ------------------------------------------------------------
-- 你這次提供的「成績單外頁說明.txt」把每一項的「原始分數」跟「換算成最終佔比後的
-- 影響」兩個數字都寫出來了：
--   全勤 +100分 (+3%)　曠課 -3.33分 (-0.10%)　遲到 -0.67分 (-0.02%)
--   事假 -1.67分 (-0.05%)　病假 -0.00分　公假 -0.00分
-- 這正好讓我抓到一個我自己造成、之前完全沒發現的問題：
--
-- sql/48fix_attendance_score_formula.sql 把「出缺席」改成跟其他科目一樣，用
-- 「原始分數 × 科目比重(3%)」的方式計入總分（見該檔案說明）。在那之前（round 6/7
-- 討論時），`conduct_point_defaults` 裡「曠課/遲到/事假」存的是-0.1／-0.02／-0.05
-- 這組**已經是最終影響數字**的小數值（那時候的算法是「直接把這個數字加到總分，
-- 不會再乘任何比重」）。sql/48 把算法改成「原始分數 × 3%」之後，這組資料庫裡
-- 舊的小數值等於被**又乘了一次3%**（-0.1 × 0.03 = -0.003），影響力變成只有預期的
-- 三十分之一，幾乎跟沒扣到一樣——這正是前幾輪「平均算出來的數字跟預期對不太起來」
-- 系列問題的其中一塊拼圖，只是當時我沒有你的原始扣分基準可以核對，一直沒抓到。
--
-- 這裡直接把 `conduct_point_defaults` 更新成「原始分數」欄的數值（-3.33／-0.67／
-- -1.67／0／0），乘上3%比重後，換算出來的最終影響就會正確對上你文件裡「(-0.10%)」
-- 「(-0.02%)」「(-0.05%)」這幾個數字。
--
-- 這是直接覆蓋資料庫裡現有的數值——如果你們已經透過【整體佔比與加扣分規則】頁
-- 自己手動調整過這幾個項目的數字（例如改成貴校最新的規定），這份檔案套用後會
-- 蓋掉那些手動調整，麻煩先確認過再執行；如果就是要對齊這次附的說明文件，直接
-- 套用即可。
-- ============================================================

insert into conduct_point_defaults (item, points) values
  ('曠課', -3.33),
  ('遲到', -0.67),
  ('事假', -1.67),
  ('病假', 0.00),
  ('公假', 0.00)
on conflict (item) do update set points = excluded.points;

